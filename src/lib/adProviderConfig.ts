export function mergeAdUnitsWithOverrides(overrides: ManagedAdUnitConfig[]): ManagedAdUnitConfig[] {
  const overrideMap = new Map(overrides.map((u) => [u.id, u]));
  return DIGITAL_HUB_AD_PROVIDER_CONFIG.map((base) => {
    const ov = overrideMap.get(base.id);
    if (!ov) return base;
    return {
      ...base,
      enabled: typeof ov.enabled === 'boolean' ? ov.enabled : base.enabled,
      placements: Array.isArray(ov.placements) && ov.placements.length > 0 ? ov.placements : base.placements,
      showOnMobile: typeof ov.showOnMobile === 'boolean' ? ov.showOnMobile : base.showOnMobile,
      showOnDesktop: typeof ov.showOnDesktop === 'boolean' ? ov.showOnDesktop : base.showOnDesktop,
      priority: typeof ov.priority === 'number' ? ov.priority : base.priority,
      rotationSeconds: typeof ov.rotationSeconds === 'number' ? ov.rotationSeconds : base.rotationSeconds,
      supportsRewardedVerification:
        typeof ov.supportsRewardedVerification === 'boolean'
          ? ov.supportsRewardedVerification
          : base.supportsRewardedVerification,
      loadStatus: ov.loadStatus || base.loadStatus,
      lastError: ov.lastError || base.lastError,
      updatedAt: ov.updatedAt,
    };
  });
}
