export const DEFAULT_PRODUCTS: Product[] = RAW_DEFAULT_PRODUCTS.map((product) => {
  // Strictly separate supplier cost from customer-facing compare-at price (zero supplier cost leakage!)
  const sanitizedPackages = (product.packages || []).map((pk) => {
    const rawOrig = pk.originalPriceBdt;
    const isSupplierCost = typeof rawOrig === 'number' && rawOrig > 0 && rawOrig <= pk.priceBdt;
    const nextPkg = { ...pk };
    if (isSupplierCost) {
      nextPkg.supplierPriceBdt = pk.supplierPriceBdt ?? rawOrig;
      delete nextPkg.originalPriceBdt;
    }
    return nextPkg;
  });

  const rawProdOrig = product.originalPriceBdt;
  const prodOrigIsSupplier =
    typeof rawProdOrig === 'number' && rawProdOrig > 0 && rawProdOrig <= product.priceBdt;

  const cleanBase: Product = {
    ...product,
    packages: sanitizedPackages.length > 0 ? sanitizedPackages : product.packages,
    catalogSectionId: product.catalogSectionId ?? getProductCatalogSectionId(product),
    stockCount: product.stockCount ?? getProductStockCount(product),
    orderFormType: product.orderFormType ?? getProductOrderFormType(product),
  };

  if (prodOrigIsSupplier) {
    cleanBase.supplierPriceBdt = product.supplierPriceBdt ?? rawProdOrig;
    delete cleanBase.originalPriceBdt;
    cleanBase.discountPercent = 0;
  } else if (typeof rawProdOrig === 'number' && rawProdOrig > product.priceBdt) {
    cleanBase.discountPercent = Math.min(
      95,
      Math.max(1, Math.round(((rawProdOrig - product.priceBdt) / rawProdOrig) * 100))
    );
  }

  const details = buildCompleteServiceDetails(cleanBase);
  return {
    ...cleanBase,
    ...details,
  };
});

